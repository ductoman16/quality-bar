import assert from "node:assert/strict";
import { test } from "node:test";

import {
  APPLICABILITY_RULE_PROFILE,
  evaluateApplicabilityRule,
} from "../src/applicability/applicability-evaluation.ts";

const textChange = {
  added: false,
  after_path: "src/current.js",
  before_path: "src/legacy.js",
  deleted: false,
  id: "file-change-2",
  modified: true,
  renamed: true,
};
const binaryAddition = {
  added: true,
  after_content: { state: "binary" },
  after_path: "assets/logo.bin",
  before_content: { state: "absent" },
  before_path: null,
  deleted: false,
  id: "file-change-1",
  modified: false,
  renamed: false,
};
const matchesPath = () => {
  throw new Error("Content-only Applicability must not match paths");
};

test("content predicates search complete text and do not classify generated text specially", () => {
  const source =
    'file_changes.exists(file, file.after_content.matches("雪だるま.*generated"))';
  assert.deepEqual(
    evaluateApplicabilityRule(
      source,
      {
        file_changes: [
          {
            ...textChange,
            after_content: {
              state: "text",
              value: "prefix\n雪だるま text generated by a tool\nsuffix",
            },
            before_content: { state: "text", value: "before" },
            generated: true,
          },
        ],
      },
      { matchesPath },
    ),
    {
      evidence: {
        kind: "matched",
        matches: [
          {
            after_path: "src/current.js",
            before_path: "src/legacy.js",
            branch_ids: ["branch-1"],
            file_change_id: "file-change-2",
            predicate_ids: ["predicate-1", "predicate-2"],
            sides: ["after"],
          },
        ],
      },
      outcome: "applicable",
      profile: APPLICABILITY_RULE_PROFILE,
      source,
    },
  );
});

test("absent and binary content stay outside positive and negated content predicates", () => {
  for (const source of [
    'file_changes.exists(file, file.before_content.matches("anything"))',
    'file_changes.exists(file, !file.before_content.matches("anything"))',
    'file_changes.exists(file, file.after_content.matches("anything"))',
    'file_changes.exists(file, !file.after_content.matches("anything"))',
  ]) {
    assert.equal(
      evaluateApplicabilityRule(
        source,
        { file_changes: [binaryAddition] },
        { matchesPath },
      ).outcome,
      "not_applicable",
      source,
    );
  }
});

test("content is read only for a relevant branch and preserves its owning failure", () => {
  let reads = 0;
  const source =
    'file_changes.exists(file, file.after_content.matches("current"))';
  const changeset = { file_changes: [textChange] };
  assert.equal(
    evaluateApplicabilityRule(`true || ${source}`, changeset, {
      matchesPath,
      readContent() {
        reads += 1;
        return { state: "text", value: "current" };
      },
    }).outcome,
    "applicable",
  );
  assert.equal(reads, 0);

  const result = evaluateApplicabilityRule(source, changeset, {
    matchesPath,
    readContent() {
      reads += 1;
      throw Object.assign(
        new Error("The frozen head side could not be read."),
        {
          code: "applicability_file_side_unreadable",
        },
      );
    },
  });
  assert.equal(reads, 1);
  assert.deepEqual(result.error, {
    code: "applicability_file_side_unreadable",
    detail: "The frozen head side could not be read.",
    file_change_id: "file-change-2",
    predicate_id: "predicate-2",
    side: "after",
  });
  assert.equal(result.outcome, "error");
});

test("required content without a reader produces an exact Applicability error", () => {
  const source =
    'file_changes.exists(file, file.after_content.matches("current"))';
  assert.deepEqual(
    evaluateApplicabilityRule(
      source,
      { file_changes: [textChange] },
      {
        matchesPath,
      },
    ),
    {
      error: {
        code: "applicability_file_side_unavailable",
        detail:
          "Frozen File Change content is unavailable for Applicability evaluation",
        file_change_id: "file-change-2",
        predicate_id: "predicate-2",
        side: "after",
      },
      outcome: "error",
      profile: APPLICABILITY_RULE_PROFILE,
      source,
    },
  );
});

test("an invalid content reader fails before evaluating even an irrelevant rule", () => {
  assert.throws(
    () =>
      evaluateApplicabilityRule(
        "true",
        { file_changes: [textChange] },
        {
          matchesPath,
          readContent: "invalid" as any,
        },
      ),
    (error) =>
      error instanceof TypeError &&
      error.message === "Applicability content reader is invalid",
  );
});

test("an earlier content match cannot conceal a later required-side failure", () => {
  const source =
    'file_changes.exists(file, file.after_content.matches("current"))';
  const earlierMatch = {
    added: true,
    after_path: "src/earlier.js",
    before_path: null,
    deleted: false,
    id: "file-change-1",
    modified: false,
    renamed: false,
  };
  const result = evaluateApplicabilityRule(
    source,
    { file_changes: [earlierMatch, textChange] },
    {
      matchesPath,
      readContent(fileChange) {
        if (fileChange.id === "file-change-1") {
          return { state: "text", value: "current" };
        }
        throw Object.assign(
          new Error("The frozen head side could not be read."),
          { code: "applicability_file_side_unreadable" },
        );
      },
    },
  );
  assert.equal(result.outcome, "error");
  assert.deepEqual(result.error, {
    code: "applicability_file_side_unreadable",
    detail: "The frozen head side could not be read.",
    file_change_id: "file-change-2",
    predicate_id: "predicate-2",
    side: "after",
  });
});
